def day_duration(days):
    word='дней' if 11<=days%100<=14 else 'день' if days%10==1 else 'дня' if days%10 in (2,3,4) else 'дней'
    return f'{days} {word}'


def number_words(value,feminine=False):
    ones=('','одну' if feminine else 'один','две' if feminine else 'два','три','четыре','пять','шесть','семь','восемь','девять')
    teens=('десять','одиннадцать','двенадцать','тринадцать','четырнадцать','пятнадцать','шестнадцать','семнадцать','восемнадцать','девятнадцать')
    tens=('','','двадцать','тридцать','сорок','пятьдесят','шестьдесят','семьдесят','восемьдесят','девяносто')
    if value>=100:
        return 'сто'+(' '+number_words(value-100,feminine) if value>100 else '')
    if value<10:
        return ones[value]
    if value<20:
        return teens[value-10]
    return tens[value//10]+(' '+ones[value%10] if value%10 else '')


def vehicle_duration_options(unit,longstanding=False):
    ranges={'days':(21,180) if longstanding else (2,90),
            'weeks':(3,52) if longstanding else (1,26),
            'months':(1,24) if longstanding else (1,18)}
    forms={'days':('день','дня','дней'),'weeks':('неделю','недели','недель'),
           'months':('месяц','месяца','месяцев')}
    lower,upper=ranges[unit]
    result=[]
    for value in range(lower,upper+1):
        index=2 if 11<=value%100<=14 else 0 if value%10==1 else 1 if value%10 in (2,3,4) else 2
        noun=forms[unit][index]
        result.extend((f'{value} {noun}',f'{number_words(value,unit=="weeks")} {noun}'))
    if unit=='months':
        result.extend(('полтора месяца','полгода','почти год','больше года'))
    return tuple(result)


